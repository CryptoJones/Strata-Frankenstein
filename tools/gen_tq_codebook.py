#!/usr/bin/env python3
"""Lloyd-Max centroids for TurboQuant's per-coordinate Beta(d/2, d/2) distribution.

TurboQuant (Zandieh et al., arXiv 2504.19874) rotates each K/V vector, so its coordinates follow a
concentrated Beta(d/2, d/2) on [-1, 1]; the optimal scalar quantizer is the Lloyd-Max one for that
distribution.  The centroids are data-oblivious (one codebook per bit width, no calibration), so they
are computed once here and embedded in kv_tq.cu.

Usage: python3 tools/gen_tq_codebook.py > src/kernels/cuda/kv_tq_codebook.inc
"""
import numpy as np
from math import lgamma

D = 256
a = D / 2
x = np.linspace(-1.0, 1.0, 262145)
logp = (a - 1) * (np.log1p(x) + np.log1p(-x)) - (2 * lgamma(a) - lgamma(2 * a)) - (2 * a - 1) * np.log(2)
p = np.exp(logp)
p[0] = p[-1] = 0.0
p /= np.trapezoid(p, x)
dx = x[1] - x[0]
cdf = np.cumsum(p) * dx
cdf /= cdf[-1]


def lloyd(n):
    c = np.interp((np.arange(n) + 0.5) / n, cdf, x)
    for _ in range(400):
        b = (c[:-1] + c[1:]) / 2
        idx = np.searchsorted(b, x)
        cnt = np.bincount(idx, weights=p, minlength=n)
        sx = np.bincount(idx, weights=x * p, minlength=n)
        new = np.where(cnt > 0, sx / np.maximum(cnt, 1e-300), c)
        if np.max(np.abs(new - c)) < 1e-9:
            c = new
            break
        c = new
    return c


print("// Generated by tools/gen_tq_codebook.py -- Lloyd-Max centroids for Beta(%d, %d) on [-1, 1]." % (D // 2, D // 2))
print("// Do not edit by hand.")
for bits in (3, 4, 6, 8):
    n = 1 << bits
    c = lloyd(n)
    print(f"static __device__ __constant__ float TQ_CENT_{bits}[{n}] = {{")
    for i in range(0, n, 8):
        print("    " + ", ".join(f"{v:.8f}f" for v in c[i:i + 8]) + ",")
    print("};")
